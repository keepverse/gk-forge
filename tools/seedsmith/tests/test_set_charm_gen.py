class CapabilityListTests(unittest.TestCase):
    """The capability list the brief prints must be spellable in the schema's closed `family` enum.

    ⛔ The defect these pin, measured rather than inferred: the brief printed `p.pick_id` for the
    capability pool, and for an elemental pick `pick_id` IS `f"{family}.{variant}"` — so 21 of the 69
    printed picks were `atom.deathblast.fire`-shaped. The schema's closed `family` enum comes from
    `distribute.capability_family_ids`, which returns UNIQUE BASE family ids (51, none carrying an
    element suffix), and `answers.schema_defects` enforces that enum on the way IN. So those 21
    spellings were refusable at the door — which is why `seedfile.resolve_capability`, whose own
    docstring records this exact echo as "legal, unambiguous" and tries it FIRST, could never run.

    These are behavioural assertions against the real vocabulary, not string matches on the brief:
    they fail on the pre-fix brief because the illegal tokens are physically present in it.
    """

    @classmethod
    def setUpClass(cls) -> None:
        cls.tuning = tuning_mod.load()
        cls.vocab = vocab_mod.build(cls.tuning)
        # The SAME theme the pre-existing no-truncation test uses, so the two cover one another: a
        # brief that differs by theme would have to fail here too, not just there.
        cls.brief = brief_mod.build_set_brief(
            themes_mod.generatable(themes_mod.load_species_themes())[0], cls.tuning, cls.vocab)
        cls.enum = set(
            schema_mod.set_schema(cls.tuning, vocabulary=cls.vocab)
            ["properties"]["capability"]["properties"]["family"]["enum"])
        # The brief offers the DISTRIBUTED pools, not the raw vocabulary: `atom.resilience` and
        # `atom.warding` are filtered out of the legal set stat pool, so asserting against
        # `vocab.stat` would assert the absence of a family the brief is right to omit.
        cls.stat_pool = distribute.legal_set_stat_pool(cls.vocab, cls.tuning)

    def _section_text(self, header: str, following: str) -> "str":
        self.assertIn(header, self.brief, f"the {header!r} header moved; update this helper")
        return self.brief.split(header, 1)[1].split(following, 1)[0]

    def _offered_tokens(self) -> "list[str]":
        """The family ids the capability list actually OFFERS, one per line.

        A line is `  - <family>[  (roles: ...)][   elements: ...]`, so the id is everything up to the
        first run of two spaces. Everything after that is annotation the model is not meant to copy.
        """
        tokens = []
        for line in self._section_text("Capability families", "Stat families").splitlines():
            stripped = line.strip()
            if not stripped.startswith("- "):
                continue
            tokens.append(stripped[2:].split("  ")[0].split("   ")[0].strip())
        return tokens

    def test_every_id_the_capability_list_prints_is_in_the_family_enum(self) -> None:
        """FAIL-BEFORE: 21 of 69 printed tokens (`atom.deathblast.fire` and siblings) are NOT in the
        enum, so a model copying one is refused before the tolerant parser can see it."""
        offered = self._offered_tokens()
        self.assertTrue(offered, "no picks parsed - the list format changed and this needs re-reading")
        illegal = sorted({t for t in offered if t not in self.enum})
        self.assertEqual(
            illegal, [],
            f"FAIL-BEFORE: these printed ids are not in the closed `family` enum, so copying one is "
            f"refused on the way in: {illegal[:5]}")

    def test_the_element_list_is_still_offered_so_no_option_is_lost(self) -> None:
        """The fix groups by family; it must not DROP any elemental option. Every variant in the
        vocabulary has to remain nameable, or the fix would narrow the pool it was meant to protect."""
        text = self._section_text("Capability families", "Stat families")
        for pick in self.vocab.capability:
            if not pick.variant:
                continue
            self.assertIn(f"  - {pick.family} ", text,
                          f"{pick.family} disappeared from the capability list")
            self.assertIn(pick.variant, text,
                          f"element {pick.variant!r} is no longer offered for {pick.family}")

    def test_every_family_in_the_vocabulary_is_still_offered_exactly_once(self) -> None:
        """Grouping must be a de-duplication, not a truncation: every family, one line each, and the
        69 underlying picks still all reachable through the element lists."""
        families = {p.family for p in self.vocab.capability}
        listed = self._offered_tokens()
        self.assertEqual(set(listed), families,
                         f"the listed families are not exactly the vocabulary's families: "
                         f"missing={sorted(families - set(listed))[:4]} "
                         f"extra={sorted(set(listed) - families)[:4]}")
        self.assertEqual(len(listed), len(set(listed)), "a family is listed on two lines")
        text = self._section_text("Capability families", "Stat families")
        self.assertEqual(text.count("elements: "),
                         len({p.family for p in self.vocab.capability if p.variant}),
                         "every elemental family must carry exactly one element list")

    def test_the_stat_list_keeps_printing_bare_pick_ids(self) -> None:
        """The capability renderer is NEW. The stat pool must be untouched: `families` is a plain
        string list there, so printing a split would break the field it feeds."""
        text = self._section_text("Stat families", "\n\nIf this theme")
        for pick in self.stat_pool:
            self.assertIn(f"  - {pick.pick_id}", text,
                          f"stat pick {pick.pick_id!r} lost its bare-id spelling")
        self.assertEqual(
            sum(1 for ln in text.splitlines() if ln.strip().startswith("- ")),
            len(self.stat_pool),
            "the stat list length changed; the fix must not touch this pool")

    def test_the_brief_states_that_capability_and_members_interact(self) -> None:
        """⛔ The third cause-class of the 61 escalations: 12 `SetCapabilityOffRole`.

        That rule (`distribute.py:210-214`) is an INTER-FIELD constraint - the capability family's own
        roles must intersect the roles the set's members claim - and the brief never mentions it. Worse,
        `capability` is item 1 and `members` is item 2, so the model is asked to pick a capability
        BEFORE the roles it has to be compatible with exist. Measured: all 69 capability picks carry
        roles, so the rule can never be skipped for any family, and the brief printed the `roles:`
        annotation that would let a model act on it without ever saying the annotation matters.

        FAIL-BEFORE: the brief said nothing about roles narrowing the capability, or about the
        consequence.
        """
        item = self.brief.split("`capability`", 1)[1].split("2. `members`", 1)[0]
        self.assertIn("SetCapabilityOffRole", item,
                      "FAIL-BEFORE: the brief never names the rule the gate enforces")
        self.assertIn("REFUSED", item,
                      "the consequence must be stated, or the rule reads as a preference")
        self.assertIn("jewel-minor-b", item,
                      "the universal escape hatch is measured (69 of 69 picks) and must be offered")

    def test_the_printed_roles_annotation_matches_the_vocabulary(self) -> None:
        """The clause above tells the model to read the `roles:` line, so that line has to be TRUE.
        This asserts it against the vocabulary rather than trusting the renderer: a `roles:` that
        understated a family would send the model to a choice the gate then refuses.

        Asserted as EXACT equality against the brief's own filter, not containment — and the filter
        matters. `roles.DROPPED_ROLES` (`head-guard`, `sense`, `ward-array`) is dropped from a
        family's roles before it reaches the brief, and correctly so: a dropped role is not one a
        member can claim, so advertising it would offer the model a role it cannot spend. Comparing
        against the raw `pick.roles` (which still carries them) is how this test first failed, and
        the code was right.
        """
        text = self._section_text("Capability families", "Stat families")
        narrowed = 0
        for pick in self.vocab.capability:
            expected = f"  - {pick.family}"
            line = next((ln for ln in text.splitlines() if ln.startswith(expected + " ")), None)
            self.assertIsNotNone(line, f"{pick.family} has no annotated line to read")
            core = [r for r in pick.roles if r in roles.HYBRID_CORE_ROLES]
            if set(pick.roles) - set(core):
                narrowed += 1
            printed: "list[str]" = []
            if "roles: " in line:
                # The line is `<family>  (roles: a, b)[   elements: x, y]` — the roles paren closes
                # BEFORE the element list, so cut at the first ')' rather than trimming from the end.
                printed = line.split("roles: ", 1)[1].split(")", 1)[0].split(", ")
            self.assertEqual(printed, core,
                             f"{pick.family}: the brief's roles line must be exactly the roles a "
                             f"member can actually claim")
        self.assertGreater(narrowed, 0,
                           "no pick had a dropped role filtered - if this ever reads 0, the filter "
                           "changed and the dropped-role reasoning above needs re-reading")

    def test_a_jewel_role_makes_the_off_role_rule_unreachable(self) -> None:
        """The escape hatch the brief now offers has to be TRUE for every family, or the advice is a
        trap. Asserted as a relationship over the whole pool, not as a family count."""
        jewel = {"jewel-major", "jewel-minor-a", "jewel-minor-b"}
        without = [p.family for p in self.vocab.capability if not (set(p.roles) & jewel)]
        self.assertEqual(without, [],
                         f"these families are not legal on ANY jewel role, so a set with a jewel "
                         f"member can still be refused: {sorted(set(without))[:5]}")


