def _entries(directory: Path, kind: str) -> "list[dict]":
    out: "list[dict]" = []
    for path in sorted(directory.glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        if doc.get("kind") != kind:
            continue
        out.extend(doc.get("entries", []))
    return out


