# run.py — RunLedger wiring: plan / resume / reconcile / overwrite
# ------------------------------------------------------------------------------------------------
class RunPlanTests(unittest.TestCase):
    def setUp(self) -> None:
        import tempfile
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.tmp_path = Path(self._tmp.name)
        # An empty, isolated "gems dir" -- no family is pre-claimed, so the pool is deterministic
        # and starts at the same three families every test run: atom.affliction, atom.arm-hardening,
        # atom.arm-riveting (confirmed against the real registry in BriefPoolTests above).
        self.gems_dir = self.tmp_path / "gems"
        self.gems_dir.mkdir()
        self.ledger_path = self.tmp_path / "gem-gen.ledger.json"

    def _answer_fn(self, subject: run_mod.Subject) -> dict:
        return _valid_answer(f"Test {subject.family_id}", f"gem.test-{subject.index}")

    def test_plan_partition_batches_and_mints_sequential_ids(self) -> None:
        plan = run_mod.plan_partition("gems/2", batch_size=3, gems_dir=self.gems_dir, ledger={})
        self.assertEqual([s.entry_id for s in plan.subjects],
                         ["gem.g2-001", "gem.g2-002", "gem.g2-003"])
        self.assertEqual([s.family_id for s in plan.subjects],
                         ["atom.affliction", "atom.arm-hardening", "atom.arm-op"])
        self.assertEqual(plan.already_done, [])
        self.assertFalse(plan.complete is True and plan.subjects)  # sanity: complete means no work

    def test_generate_partition_resume_produces_nothing_the_second_time(self) -> None:
        produced = run_mod.generate_partition(
            "gems/2", answer_fn=self._answer_fn, batch_size=3,
            ledger_path=self.ledger_path, gems_dir=self.gems_dir)
        self.assertEqual(len(produced), 3)

        produced_again = run_mod.generate_partition(
            "gems/2", answer_fn=self._answer_fn, batch_size=3,
            ledger_path=self.ledger_path, gems_dir=self.gems_dir)
        self.assertEqual(produced_again, {})

        plan = run_mod.plan_partition("gems/2", batch_size=3, gems_dir=self.gems_dir,
                                      ledger=RunLedger(self.ledger_path))
        self.assertEqual(plan.subjects, [])
        self.assertEqual(len(plan.already_done), 3)

    def test_reconcile_recovers_a_corrupted_ledger_row(self) -> None:
        run_mod.generate_partition("gems/2", answer_fn=self._answer_fn, batch_size=3,
                                   ledger_path=self.ledger_path, gems_dir=self.gems_dir)
        doc = json.loads(self.ledger_path.read_text(encoding="utf-8"))
        first_key = "gem-gems/2-atom.affliction"
        self.assertIn(first_key, doc["done"])
        doc["done"][first_key] = {"entryId": "gem.g2-001"}  # no "entry" -- a corrupted row
        self.ledger_path.write_text(json.dumps(doc), encoding="utf-8")

        plan = run_mod.plan_partition("gems/2", batch_size=3, gems_dir=self.gems_dir,
                                      ledger=RunLedger(self.ledger_path))
        self.assertEqual([s.subject_id for s in plan.subjects], [first_key])
        self.assertEqual(len(plan.already_done), 2)
        # And the id it gets reminted is the SAME one it had before -- position-derived, not
        # accidentally shifted by the other two rows still being done.
        self.assertEqual(plan.subjects[0].entry_id, "gem.g2-001")

    def test_overwrite_by_explicit_ids_only_touches_those_subjects(self) -> None:
        run_mod.generate_partition("gems/2", answer_fn=self._answer_fn, batch_size=3,
                                   ledger_path=self.ledger_path, gems_dir=self.gems_dir)
        target_id = "gem-gems/2-atom.arm-hardening"
        produced = run_mod.generate_partition(
            "gems/2", answer_fn=self._answer_fn, batch_size=3, ledger_path=self.ledger_path,
            gems_dir=self.gems_dir, overwrite=[target_id])
        self.assertEqual(list(produced.keys()), [target_id])

    def test_overwrite_all_requires_the_literal_string(self) -> None:
        run_mod.generate_partition("gems/2", answer_fn=self._answer_fn, batch_size=3,
                                   ledger_path=self.ledger_path, gems_dir=self.gems_dir)
        produced = run_mod.generate_partition(
            "gems/2", answer_fn=self._answer_fn, batch_size=3, ledger_path=self.ledger_path,
            gems_dir=self.gems_dir, overwrite="all")
        self.assertEqual(len(produced), 3)

    def test_a_typo_d_overwrite_scope_fails_loudly_not_silently(self) -> None:
        with self.assertRaises(ValueError):
            run_mod.generate_partition(
                "gems/2", answer_fn=self._answer_fn, batch_size=3, ledger_path=self.ledger_path,
                gems_dir=self.gems_dir, overwrite="al")  # a typo of "all", not a list

    def test_apply_answer_raises_blocked_for_a_legal_decline(self) -> None:
        plan = run_mod.plan_partition("gems/2", batch_size=1, gems_dir=self.gems_dir, ledger={})
        subject = plan.subjects[0]
        with self.assertRaises(run_mod.Blocked):
            run_mod.apply_answer(subject, {BLOCKED_FIELD: "no fitting name"})

    def test_apply_answer_raises_value_error_for_a_malformed_answer(self) -> None:
        plan = run_mod.plan_partition("gems/2", batch_size=1, gems_dir=self.gems_dir, ledger={})
        subject = plan.subjects[0]
        with self.assertRaises(ValueError):
            run_mod.apply_answer(subject, {"name": "X", "nameKey": "not-legal"})

    def test_apply_answer_copies_family_tags_and_resolves_power_band_by_position(self) -> None:
        plan = run_mod.plan_partition("gems/2", batch_size=3, gems_dir=self.gems_dir, ledger={})
        entries = [run_mod.apply_answer(s, _valid_answer(f"N{i}", f"gem.n{i}"))
                  for i, s in enumerate(plan.subjects)]
        self.assertEqual([e["powerBand"] for e in entries], ["medium", "high", "low"])
        self.assertEqual(entries[0]["tags"], ["offensive"])       # atom.affliction
        self.assertEqual(entries[1]["tags"], ["defensive"])       # atom.arm-hardening

    def test_apply_answer_omits_affinity_when_the_element_answer_is_omni(self) -> None:
        # Regression for item-seed-regen cause 8b/3 (GemAffinityNotConcrete, gem.g1-007): an
        # elemental family's model answer legally includes "omni" for `element` -- apply_answer
        # must not forward that same value into `affinityElement`, which must always be concrete.
        family_row = {"id": "atom.elemental-power", "tags": ["offensive"],
                     "variants": {"generate": "elements+omni"}}
        subject = run_mod.Subject(
            subject_id="gem-gems/1-atom.elemental-power", partition="gems/1",
            family_id="atom.elemental-power", family_row=family_row, entry_id="gem.g1-007",
            index=2, brief="")
        self.assertTrue(subject.elemental)
        entry = run_mod.apply_answer(
            subject, {"name": "Primal Shard", "nameKey": "gem.primal-shard", "element": "omni"})
        self.assertEqual(entry["element"], "omni")
        self.assertNotIn("affinityElement", entry)

    def test_apply_answer_keeps_affinity_concrete_when_the_element_answer_is_concrete(self) -> None:
        family_row = {"id": "atom.elemental-power", "tags": ["offensive"],
                     "variants": {"generate": "elements+omni"}}
        subject = run_mod.Subject(
            subject_id="gem-gems/1-atom.elemental-power", partition="gems/1",
            family_id="atom.elemental-power", family_row=family_row, entry_id="gem.g1-001",
            index=0, brief="")
        entry = run_mod.apply_answer(
            subject, {"name": "Ember Shard", "nameKey": "gem.ember-shard", "element": "fire"})
        self.assertEqual(entry["element"], "fire")
        self.assertEqual(entry["affinityElement"], "fire")

    def test_write_partition_file_round_trips_the_shipped_shape(self) -> None:
        plan = run_mod.plan_partition("gems/2", batch_size=2, gems_dir=self.gems_dir, ledger={})
        entries = [run_mod.apply_answer(s, _valid_answer(f"N{i}", f"gem.n{i}"))
                  for i, s in enumerate(plan.subjects)]
        target = run_mod.write_partition_file("gems/2", entries,
                                              path=self.tmp_path / "g2.json",
                                              model="test-model")
        doc = json.loads(target.read_text(encoding="utf-8"))
        self.assertEqual(doc["schemaVersion"], 1)
        self.assertEqual(doc["kind"], "gem")
        self.assertEqual(doc["_meta"]["partition"], "gems/2")
        self.assertEqual(len(doc["entries"]), 2)
        self.assertEqual(doc["entries"], entries)

    def test_write_partition_file_preserves_existing_entries(self) -> None:
        """A partial ledger must never be allowed to replace a real partition on disk."""
        target = self.tmp_path / "g2.json"
        existing = {"id": "gem.g2-001", "name": "Existing Gem", "family": "atom.affliction"}
        fresh = {"id": "gem.g2-002", "name": "Fresh Gem", "family": "atom.arm-hardening"}

        run_mod.write_partition_file("gems/2", [existing], path=target, model="test-model")
        run_mod.write_partition_file("gems/2", [fresh], path=target, model="test-model")

        doc = json.loads(target.read_text(encoding="utf-8"))
        self.assertEqual([entry["id"] for entry in doc["entries"]],
                         ["gem.g2-001", "gem.g2-002"])

    def test_plan_partition_continues_after_an_existing_gem_sequence(self) -> None:
        existing = {
            "schemaVersion": 1,
            "kind": "gem",
            "_meta": {"partition": "gems/1"},
            "entries": [{"id": "gem.g1-001", "family": "atom.affliction"}],
        }
        (self.gems_dir / "g1.json").write_text(json.dumps(existing), encoding="utf-8")

        plan = run_mod.plan_partition("gems/1", batch_size=1, gems_dir=self.gems_dir, ledger={})

        self.assertEqual([subject.entry_id for subject in plan.subjects], ["gem.g1-002"])


