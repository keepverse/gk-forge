class SchemaTests(unittest.TestCase):
    def test_the_schema_is_audit_schema_clean_flat_and_elemental(self) -> None:
        for elemental in (False, True):
            with self.subTest(elemental=elemental):
                self.assertEqual(audit_schema(schema_mod.gem_answer_schema(elemental=elemental)), [])

    def test_the_schema_names_no_magnitude_field(self) -> None:
        text = json.dumps([schema_mod.gem_answer_schema(elemental=False),
                           schema_mod.gem_answer_schema(elemental=True)])
        for banned in ('"tier"', '"cost"', '"powerBand"', '"weight"'):
            self.assertNotIn(banned, text)

    def test_validate_answer_accepts_a_well_formed_flat_answer(self) -> None:
        errors = schema_mod.validate_answer(_valid_answer("Afflicted Barb", "gem.afflicted-barb"),
                                            elemental=False)
        self.assertEqual(errors, [])

    def test_validate_answer_rejects_a_bad_name_key(self) -> None:
        errors = schema_mod.validate_answer(_valid_answer("X", "not-a-gem-key"), elemental=False)
        self.assertTrue(errors)

    def test_validate_answer_rejects_an_empty_name(self) -> None:
        errors = schema_mod.validate_answer({"name": "", "nameKey": "gem.x"}, elemental=False)
        self.assertTrue(errors)

    def test_validate_answer_requires_element_when_elemental(self) -> None:
        errors = schema_mod.validate_answer(_valid_answer("Ember Shard", "gem.ember-shard"),
                                            elemental=True)
        self.assertTrue(any("element" in e for e in errors))

    def test_validate_answer_accepts_a_legal_element_when_elemental(self) -> None:
        answer = {"name": "Ember Shard", "nameKey": "gem.ember-shard", "element": "fire"}
        self.assertEqual(schema_mod.validate_answer(answer, elemental=True), [])

    def test_validate_answer_rejects_an_element_when_not_elemental(self) -> None:
        answer = {"name": "X", "nameKey": "gem.x", "element": "fire"}
        errors = schema_mod.validate_answer(answer, elemental=False)
        self.assertTrue(errors)

    def test_validate_answer_blocked_short_circuits_every_other_check(self) -> None:
        errors = schema_mod.validate_answer({BLOCKED_FIELD: "no fitting name", "name": ""},
                                            elemental=False)
        self.assertEqual(errors, [])


