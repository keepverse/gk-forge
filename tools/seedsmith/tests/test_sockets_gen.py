"""Tests for item module 4, `sockets-gen` (docs/architecture/item-seedgen/spec-sockets-gen.md).

    python -m pytest gk-forge/tools/seedsmith/tests/test_sockets_gen.py -v

Two kinds of assertion here, deliberately kept apart:

- **Harness-mechanics tests** (`EmitTests`, `SchemaTests`, `BriefPoolTests`, `RunPlanTests`) run
  against an isolated `tmp_path` gems directory and ledger file — they prove `plan`/`resume`/
  `reconcile`/`overwrite`/id-minting work in general, the same way `test_run_ledger.py` proves
  `RunLedger` works in general.
- **Real-corpus tests** (`RealGemsCorpusTests`) run against the actual, committed
  `gk-data/packs/fusion/data/seed/items/gems/*.json` — mirroring `test_set_charm_gen.py`'s own precedent ("almost every
  assertion here runs against the REAL shipped corpus... that is what caught the two defects this
  module reports"). These are what prove the module's own acceptance criterion 2: the
  allocated-but-never-authored `gems/2` partition (confirmed empty by `allocated_partitions.json`
  naming `gems/1,2,3` while only `g1.json`/`g3.json` existed on disk) now has a real, importable
  file, generated by this module's own tool.
"""
