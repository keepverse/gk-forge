# brief.py — the unauthored-family pool
# ------------------------------------------------------------------------------------------------
class BriefPoolTests(unittest.TestCase):
    def test_unauthored_families_excludes_families_already_claimed_by_a_shipped_gem(self) -> None:
        claimed = brief_mod.used_families()
        pool_ids = {row["id"] for row in brief_mod.unauthored_families(limit=None)}
        self.assertFalse(claimed & pool_ids, "a claimed family must never re-appear in the pool")

    def test_unauthored_families_excludes_elemental_variant_families(self) -> None:
        for row in brief_mod.unauthored_families(limit=None):
            self.assertFalse(brief_mod.is_elemental(row), f"{row['id']} is elemental variant")

    def test_unauthored_families_is_sorted_and_deterministic(self) -> None:
        first = [row["id"] for row in brief_mod.unauthored_families(limit=10)]
        second = [row["id"] for row in brief_mod.unauthored_families(limit=10)]
        self.assertEqual(first, second)
        self.assertEqual(first, sorted(first))

    def test_used_families_reads_the_real_gems_dir_fresh(self) -> None:
        claimed = brief_mod.used_families()
        # g1.json/g3.json ship real families; a fresh read must see them without being told to.
        self.assertIn("atom.might", claimed)
        self.assertIn("atom.bulwark", claimed)

    def test_build_gem_brief_never_offers_a_number_or_a_tag(self) -> None:
        """The brief may (and does) TELL the model it must never pick a tier/power band/tag —
        that instruction text legitimately contains those words, the same way `setgen/brief.py`'s
        own "Never choose a number, a strength, a duration or a tier" does. What must never appear
        is the family's OWN authored tag value leaking into the brief as if it were offered."""
        row = {"id": "atom.affliction", "name": "Affliction", "tags": ["offensive"]}
        text = brief_mod.build_gem_brief(row)
        self.assertNotIn("`tags`", text)
        self.assertNotIn("`powerBand`", text)
        self.assertNotIn("offensive", text)
        self.assertNotIn("defensive", text)

    def test_build_gem_brief_offers_element_only_when_elemental(self) -> None:
        flat = {"id": "atom.affliction", "name": "Affliction"}
        elemental = {"id": "atom.deathblast", "name": "Deathblast",
                    "variants": {"generate": "elements+omni"}}
        self.assertNotIn("`element`", brief_mod.build_gem_brief(flat))
        self.assertIn("`element`", brief_mod.build_gem_brief(elemental))


