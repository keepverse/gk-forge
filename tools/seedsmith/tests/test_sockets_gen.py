# emit.py — ids, icon keys, the power-band rotation, and the final entry shape
# ------------------------------------------------------------------------------------------------
class EmitTests(unittest.TestCase):
    def test_mint_gem_id_uses_partition_slot_verbatim(self) -> None:
        self.assertEqual(emit.mint_gem_id("gems/2", 14), "gem.g2-014")
        self.assertEqual(emit.mint_gem_id("gems/1", 1), "gem.g1-001")

    def test_mint_gem_id_refuses_out_of_range_seq(self) -> None:
        with self.assertRaises(emit.IdRefused):
            emit.mint_gem_id("gems/2", 0)
        with self.assertRaises(emit.IdRefused):
            emit.mint_gem_id("gems/2", 900)

    def test_mint_gem_id_refuses_a_non_gems_partition(self) -> None:
        with self.assertRaises(emit.IdRefused):
            emit.mint_gem_id("charms/econ", 1)
        with self.assertRaises(emit.IdRefused):
            emit.mint_gem_id("gems/0", 1)

    def test_resolve_power_band_is_a_deterministic_three_step_rotation(self) -> None:
        bands = [emit.resolve_power_band(i) for i in range(6)]
        self.assertEqual(bands, ["medium", "high", "low", "medium", "high", "low"])

    def test_resolve_power_band_refuses_negative_index(self) -> None:
        with self.assertRaises(emit.IdRefused):
            emit.resolve_power_band(-1)

    def test_icon_key_derives_from_name_key(self) -> None:
        self.assertEqual(emit.icon_key("gem.ember-shard"), "icon.gem.ember-shard")

    def test_icon_key_refuses_a_malformed_name_key(self) -> None:
        with self.assertRaises(emit.IdRefused):
            emit.icon_key("not-a-gem-key")

    def test_assemble_entry_field_order_matches_the_shipped_shape(self) -> None:
        entry = emit.assemble_entry(
            entry_id="gem.g2-001", name_key="gem.afflicted-barb", name="Afflicted Barb",
            family_id="atom.affliction", power_band="medium", tags=("offensive",),
        )
        # id, nameKey, name, family, [element], powerBand, [affinityElement], iconKey, tags —
        # entry-shapes.md §1's own example order, with element/affinityElement omitted here since
        # this family has no per-element variant.
        self.assertEqual(list(entry.keys()),
                         ["id", "nameKey", "name", "family", "powerBand", "iconKey", "tags"])
        self.assertEqual(entry["iconKey"], "icon.gem.afflicted-barb")
        self.assertEqual(entry["tags"], ["offensive"])

    def test_assemble_entry_includes_element_and_affinity_when_given(self) -> None:
        entry = emit.assemble_entry(
            entry_id="gem.g1-001", name_key="gem.ember-shard", name="Ember Shard",
            family_id="atom.elemental-power", power_band="medium", tags=("offensive",),
            element="fire", affinity_element="fire",
        )
        self.assertEqual(list(entry.keys()),
                         ["id", "nameKey", "name", "family", "element", "powerBand",
                          "affinityElement", "iconKey", "tags"])

    def test_assemble_entry_refuses_a_family_id_with_no_atom_prefix(self) -> None:
        with self.assertRaises(emit.IdRefused):
            emit.assemble_entry(entry_id="gem.g2-001", name_key="gem.x", name="X",
                                family_id="not-an-atom", power_band="medium", tags=())

    def test_assemble_entry_refuses_a_power_band_outside_the_rotation(self) -> None:
        with self.assertRaises(emit.IdRefused):
            emit.assemble_entry(entry_id="gem.g2-001", name_key="gem.x", name="X",
                                family_id="atom.affliction", power_band="extreme", tags=())

    def test_assemble_entry_refuses_an_empty_name(self) -> None:
        with self.assertRaises(emit.IdRefused):
            emit.assemble_entry(entry_id="gem.g2-001", name_key="gem.x", name="",
                                family_id="atom.affliction", power_band="medium", tags=())

    def test_assemble_entry_refuses_omni_as_a_socket_affinity(self) -> None:
        # item-seed-regen cause 8b/3 (GemAffinityNotConcrete): omni is a legal `element` pick (the
        # additive baseline of an "elements+omni" family) but never a legal socket affinity -- a
        # caller must omit affinityElement (None), never forward the element pick verbatim.
        with self.assertRaises(emit.IdRefused):
            emit.assemble_entry(
                entry_id="gem.g1-001", name_key="gem.primal-shard", name="Primal Shard",
                family_id="atom.elemental-power", power_band="low", tags=("offensive",),
                element="omni", affinity_element="omni",
            )

    def test_assemble_entry_accepts_omni_as_element_when_affinity_is_omitted(self) -> None:
        entry = emit.assemble_entry(
            entry_id="gem.g1-001", name_key="gem.primal-shard", name="Primal Shard",
            family_id="atom.elemental-power", power_band="low", tags=("offensive",),
            element="omni", affinity_element=None,
        )
        self.assertEqual(entry["element"], "omni")
        self.assertNotIn("affinityElement", entry)


